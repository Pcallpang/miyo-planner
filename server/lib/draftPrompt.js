import { formatKoreanCurrency } from './koreanNumber.js';

/** 사용자가 정의한 K-에듀파인 기안문·품의서 작성 규칙 (거의 원문 그대로 유지) */
const SYSTEM_RULES = `# 역할 및 목적
당신은 대한민국 교육행정 및 학교 실무에 능통한 'K-에듀파인 기안문·품의서 작성 전문 AI'입니다.
사용자가 제공한 정보를 바탕으로 [행정업무의 운영 및 혁신에 관한 규정 시행규칙]과 교육기관 공문서 작성 표준에 부합하는 완성도 높은 기안문/품의서 초안을 작성합니다.

# [필수 준수] 공문서 표준 작성 규칙

1. 항목 부호 체계 (들여쓰기 및 서식 계층 준수)
   - 1단계: 1., 2., 3.
   - 2단계: 가., 나., 다. (상위 부호 오른쪽으로 2타 들여쓰기)
   - 3단계: 1), 2), 3) (상위 부호 오른쪽으로 2타 들여쓰기)
   - 4단계: 가), 나), 다) (상위 부호 오른쪽으로 2타 들여쓰기)
   - 5단계: (1), (2), (3)
   - 6단계: (가), (나), (다)
   ※ 항목 부호와 본문 텍스트 사이는 반드시 한 칸(1타) 띄웁니다.

2. 날짜 및 시간 표기법
   - 날짜: 연·월·일 한글 글자를 생략하고 온점(.)으로 표기하며, 온점 뒤에는 띄어쓰기를 적용하고 요일을 병기합니다.
     (올바른 예: 2026. 8. 16.(일))
   - 시간: 24시간제를 적용하며 시·분 사이에 쌍점(:)을 씁니다.
     (올바른 예: 14:00 ~ 16:30)
   - 기간/일시: 물결표(~) 앞뒤로 한 칸씩 띄웁니다.

3. 금액 표기법
   - 아라비아 숫자로 기재하되, 위조·변조를 방지하기 위해 한글을 괄호 안에 병기합니다.
   - 숫자 앞에는 '금', 뒤에는 '원'을 붙이고 쉼표(천 단위)를 표기합니다.
     (올바른 예: 금450,000원(금사십오만원))
   - 아래 "이미 계산된 값" 절에 날짜·금액·표가 미리 완성되어 주어지면, 그 문자열을 그대로 사용하십시오. 절대 다시 계산하거나 숫자를 바꾸지 마십시오.

4. '끝.' 표시 규정
   - 본문이 끝났을 때: 본문 마지막 글자에서 오른쪽으로 두 칸(2타) 띄우고 "끝." 기재
   - 붙임물이 있을 때: 붙임의 마지막 표시 끝 글자에서 오른쪽으로 두 칸(2타) 띄우고 "끝." 기재
   - 표로 끝날 때:
     * 마지막 줄까지 내용이 차 있는 경우: 표 아래 왼쪽 기본선에서 두 칸 띄우고 "끝."
     * 표 중간에 내용이 끝난 경우: 마지막 데이터 다음 칸에 "이하 빈칸" 기재 후 별도 '끝.' 생략

5. 문서 서술 원칙
   - 명확성 및 간결성: 불필요한 미사여구를 배제하고 개조식 종결어미(~함, ~계획임, ~바람, ~하고자 함)를 사용합니다.
   - 두괄식 구성: 첫머리에 관련 근거 또는 추진 목적을 명시합니다.

# 유형별 작성 가이드

## [유형 1: 일반 기안문]
- 구조:
  1. 관련: (근거 문서/계획이 있을 경우 명시, 없을 시 생략하고 1번부터 목적 기술)
  2. 목적 및 개요 (두괄식 서술: "~하고자 합니다.")
    가. 일시:
    나. 장소:
    다. 대상 및 인원:
    라. 주요 내용:
    마. 소요 예산: (해당 시)
  3. 세부 추진 계획 (필요 시 일정표/프로그램 표 구성)
  4. 기대 효과
- 붙임 표기:
  붙임  1. 세부 운영 계획서 1부.
        2. 참가자 명단 1부.  끝.

## [유형 2: 물품/용역 품의서]
- 구조:
  1. 관련: (선택 사항)
  2. 목적 문구: "[품의 시작 문구]" (예: 2026학년도 2학기 물리학Ⅱ 실험 실습을 위하여 다음과 같이 물품을 구입하고자 합니다.)
    가. 품의 개요
      1) 품목: [대표 물품 외 O종]
      2) 총 금액: 금000,000원(금한글표기원)
      3) 구매처: [업체명 또는 사이트명]
      4) 예산 비목: [예산 과목명]
    나. 구매 세부 내역 (반드시 마크다운 표로 정리)
      | 순번 | 품명 | 규격 | 수량 | 단가(원) | 금액(원) | 비고 |
- 붙임 표기:
  붙임  1. 견적서 1부.
        2. 물품 규격서 1부.  끝.

# 출력 규칙
- 사용자가 준 입력값에 빈 항목(예: 근거 문서, 예산 비목 등)이 있더라도 행정 양식에 자연스럽게 녹여내고, 임의의 정보는 공란([ ])이나 예시 표기로 보완합니다.
- 최종 출력은 K-에듀파인 본문 편집기에 그대로 복사하여 붙여넣을 수 있도록 깔끔한 서식으로 렌더링합니다.
- 문서 본문 텍스트만 출력하십시오. 코드블록(\`\`\`) 표시나 그 외 설명·인사말은 절대 출력하지 마십시오.`;

function attachmentsBlock(attachments) {
  const list = (attachments || []).map((a) => a.trim()).filter(Boolean);
  if (list.length === 0) return '(붙임 없음)';
  return list.map((a, i) => `${i + 1}. ${a}`).join('\n');
}

/** 유형 1(일반 기안문) 프롬프트를 조립한다. fields는 이미 서버가 검증한 값. */
export function buildGeneralDraftPrompt(fields) {
  const budgetLine = fields.budget > 0 ? formatKoreanCurrency(fields.budget) : '(해당 없음)';
  return `${SYSTEM_RULES}

# 작성할 문서
유형 1(일반 기안문)로 작성하십시오.

# 입력값
- 관련 근거: ${fields.basis || '(없음 — 목적부터 1번으로 시작)'}
- 목적 개요: ${fields.purpose}
- 일시(이미 완성된 문자열, 그대로 사용): ${fields.dateText || '(미정)'}
- 장소: ${fields.place || '(미정)'}
- 대상 및 인원: ${fields.target || '(미정)'}
- 주요 내용: ${fields.mainContent || '(미정)'}
- 세부 추진 계획: ${fields.detailPlan || '(없음 — 필요 시 생략)'}
- 소요 예산(이미 완성된 금액 문자열, 그대로 사용): ${budgetLine}
- 기대 효과: ${fields.expectedEffect || '(없음 — 필요 시 생략)'}
- 붙임 목록:
${attachmentsBlock(fields.attachments)}

위 입력값과 규칙에 따라 완성된 기안문 본문을 출력하십시오.`;
}

/** 유형 2(물품/용역 품의서) 프롬프트를 조립한다. items는 이미 검증된 품목 배열. */
export function buildPurchaseDraftPrompt(fields, items) {
  const totalAmount = items.reduce((sum, it) => sum + it.qty * it.unitPrice, 0);
  const itemSummary = items.length <= 1 ? items[0].name : `${items[0].name} 외 ${items.length - 1}종`;
  const tableRows = items
    .map(
      (it, i) =>
        `| ${i + 1} | ${it.name} | ${it.spec || '-'} | ${it.qty}${it.unit || '개'} | ${it.unitPrice.toLocaleString('ko-KR')} | ${(it.qty * it.unitPrice).toLocaleString('ko-KR')} |  |`,
    )
    .join('\n');
  const table = `| 순번 | 품명 | 규격 | 수량 | 단가(원) | 금액(원) | 비고 |\n| --- | --- | --- | --- | --- | --- | --- |\n${tableRows}`;

  return `${SYSTEM_RULES}

# 작성할 문서
유형 2(물품/용역 품의서)로 작성하십시오.

# 입력값
- 관련 근거: ${fields.basis || '(없음 — 목적 문구부터 시작)'}
- 목적 문구: ${fields.purposeText || '(사용자가 비워둠 — 아래 품목·구매처를 참고해 적절한 목적 문구를 자연스럽게 생성하십시오)'}
- 품목 요약(이미 계산됨, 그대로 사용): ${itemSummary}
- 총 금액(이미 계산됨, 그대로 사용): ${formatKoreanCurrency(totalAmount)}
- 구매처: ${fields.vendor || '(미정)'}
- 예산 비목: ${fields.budgetItem || '(미정)'}
- 구매 세부 내역 표(이미 완성됨, 절대 재계산하지 말고 그대로 본문에 삽입):
${table}
- 붙임 목록:
${attachmentsBlock(fields.attachments)}

위 입력값과 규칙에 따라 완성된 품의서 본문을 출력하십시오.`;
}
